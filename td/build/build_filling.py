# Build (or update) river-filling.toe, "The filling glass" (docs/files/river-filling.md; td/filling/fill.py). Idempotent:
#   .\tools\td.ps1 -File .\td\build\build_filling.py -Timeout 120
# Only runs while TouchDesigner has river-filling.toe open, in a copy of the baseline template: open
# river-baseline-template.toe, .\tools\td_save.ps1 -Target river-filling.toe, then run this.
#
#   /project1/filling   THE SHOW: filling_exec (Execute DAT, every frame) -> fill.frame(): every rope LED and screen pixel
#                       painted by where it is in the room (the pinned map and screens files, measured tilts):
#                       rope_render (Script TOP, 20x400, LED 0 on top) -> rope_canvas -> /project1/ropes
#                       panel_render (Script TOP, 512x256, the four screens upright) -> screen<k>_crop -> outputs
#   /project1/outputs   the template's screens (td/build/screens.py): screen<k>_src takes filling/screen<k>_crop.
#   /project1/ropes     Art-Net: Canvas = filling/rope_canvas, artnet_out's 1,400 W limit for both boxes.
import importlib
import sys

REPO = 'C:/Users/user/River/river-bitcube'
TOE = 'river-filling.toe'
TD_DIR = REPO + '/td'
ROPE_BRIGHTNESS, ROPE_MAXBRIGHTNESS, ROPE_BOXWATTS = 1.0, 1.0, 1500

if REPO + '/td/build' not in sys.path:
    sys.path.insert(0, REPO + '/td/build')
import registry
importlib.reload(registry)
registry.require_build(project.name, 'td/build/build_filling.py')       # never another show file
_cal = registry.calibration_for(TOE)
PIXELMAP, SCREENS = _cal['pixelmap'], _cal['screens']
proj = op('/project1')
missing = [n for n in ('inputs', 'outputs', 'ropes', 'panels') if proj.op(n) is None]
if missing:
    raise RuntimeError(f'{TOE} must be a copy of river-baseline-template.toe (missing /project1/{", /project1/".join(missing)})')

if TD_DIR not in sys.path:
    sys.path.insert(0, TD_DIR)
for _m in ('remembered.particles', 'filling.fill'):
    if _m in sys.modules:
        importlib.reload(sys.modules[_m])
from filling import fill as filling_fill                                 # noqa: E402
filling_fill.reset()


def res(o, w, h):
    o.par.outputresolution = 'custom'
    o.par.resolutionw, o.par.resolutionh = w, h


def maker(parent):
    def get(optype, name, x, y):
        o = parent.op(name) or parent.create(optype, name)
        o.nodeX, o.nodeY = x, y
        return o
    return get


fc = proj.op('filling') or proj.create(baseCOMP, 'filling')
fc.nodeX, fc.nodeY = 250, -250
fc.color = (0.1, 0.3, 0.6)
pg = next((p for p in fc.customPages if p.name == 'Filling'), None) or fc.appendCustomPage('Filling')
for _n, _f, _l in (('Mapfile', PIXELMAP, 'LED map (every rope LED in the room)'),
                   ('Screensfile', SCREENS, 'Screens (where each screen hangs)')):
    if not hasattr(fc.par, _n):
        pg.appendStr(_n, label=_l)
    getattr(fc.par, _n).val = (REPO + '/' + _f) if _f else ''
get = maker(fc)
cb = get(textDAT, 'render_callbacks', 0, -200)
cb.text = ("# Script TOP callbacks (generated by build_filling.py).\n"
           "import sys\n"
           f"if '{TD_DIR}' not in sys.path:\n    sys.path.insert(0, '{TD_DIR}')\n"
           "from filling import fill\n\n"
           "def onSetupParameters(scriptOp):\n    return\n\n"
           "def onPulse(par):\n    return\n\n"
           "def onCook(scriptOp):\n    fill.cook(scriptOp)\n")
rr = get(scriptTOP, 'rope_render', 150, -200)
rr.par.callbacks = cb
rc = get(nullTOP, 'rope_canvas', 300, -200)
rc.inputConnectors[0].connect(rr)
pr = get(scriptTOP, 'panel_render', 150, -350)
pr.par.callbacks = cb
crops = []
for k in range(1, 5):
    c = get(cropTOP, f'screen{k}_crop', 300, -350 - 100 * (k - 1))
    c.inputConnectors[0].connect(pr)
    c.par.cropleft, c.par.cropright = (k - 1) / 4, k / 4
    c.par.cropbottom, c.par.croptop = 0, 1
    crops.append(c)
ex = get(executeDAT, 'filling_exec', 0, -500)
ex.text = ("# The filling glass, every frame (generated by build_filling.py).\n"
           "import sys\n"
           f"if '{TD_DIR}' not in sys.path:\n    sys.path.insert(0, '{TD_DIR}')\n"
           "from filling import fill\n\n"
           "def onFrameStart(frame):\n    fill.frame(me.parent())\n    return\n")
ex.par.framestart = True
ex.par.active = True

# outputs: our screens and rope canvas (Select TOPs: a wire can't cross COMPs)
out_c = proj.op('outputs')
for n in ('uv_table', 'uv_chop', 'sample_ropes', 'rope_rows', 'rope_flop', 'rope_canvas'):
    o = out_c.op(n)
    if o is not None:
        o.destroy()
rope_sel = out_c.op('rope_filling') or out_c.create(selectTOP, 'rope_filling')
rope_sel.par.top = rc.path
_g = dict(globals(), SCREENS_COMP=out_c, FIELD=out_c.op('field_out'), ROPE_CANVAS=rope_sel, SCREEN_PREFIX='screen',
          PINNED_SCREENS=SCREENS, get=maker(out_c))
exec(open(REPO + '/td/build/screens.py', encoding='utf-8').read(), _g)
for k, c in enumerate(crops, start=1):
    sw = out_c.op(f'screen{k}_src')
    sel = out_c.op(f'screen{k}_filling') or out_c.create(selectTOP, f'screen{k}_filling')
    sel.par.top = c.path
    sel.nodeX, sel.nodeY = sw.nodeX - 150, sw.nodeY + 40
    if sw.inputConnectors[0].connections[:1] != [sel.outputConnectors[0]]:
        sw.inputConnectors[0].connect(sel)
out_c.par.Panelgain, out_c.par.Panelgamma = 1.0, 1.0

ropes = proj.op('ropes')
ropes.par.Canvas = rc.path
ropes.par.Cropleft = ropes.par.Cropbottom = 0
ropes.par.Cropright = ropes.par.Croptop = 1
ropes.par.Brightness, ropes.par.Maxbrightness, ropes.par.Boxwatts = ROPE_BRIGHTNESS, ROPE_MAXBRIGHTNESS, ROPE_BOXWATTS
ropes.par.Source = 'canvas'
ropes.par.Active = True

rd = proj.op('README') or proj.create(textDAT, 'README')
rd.text = (f"THE FILLING GLASS  (river-filling.toe, built by td/build/build_filling.py)\n\n"
           "Every rope and screen one canvas, by where each LED is in the room: water fills the column from the floor\n"
           "to the top, turbulent, blues and blacks, holds, then drains out. Logic: td/filling/fill.py.\n"
           f"Calibration: {PIXELMAP.rsplit('/', 1)[-1]}, {(SCREENS or '').rsplit('/', 1)[-1]} (+ measured tilts).\n"
           "Save only with tools/td_save.ps1.\n")
print('filling built | screens from', (SCREENS or '').rsplit('/', 1)[-1], '| errors:', proj.errors(recurse=True) or 'none')
